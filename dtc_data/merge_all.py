# --- Generic CSV ---
generic = {}
with open(CSV, newline="") as f:
    for row in csv.reader(f):
        if len(row) >= 2 and row[0]:
            generic[row[0].strip().upper()] = row[1].strip()

# Merge: Toyota wins, then existing DB, then generic fills gaps
added_toyota = 0
conflict_toyota = 0
for src, name in ((toyota_diesel, "diesel"), (toyota_2grfks, "2GR-FKS")):
    for code, desc in src.items():
        if code not in db:
            added_toyota += 1
            db[code] = desc
        elif db[code] != desc:
            conflict_toyota += 1
            db[code] = desc

added_generic = 0
for code, desc in generic.items():
    if code not in db:
        added_generic += 1
        db[code] = desc

print(f"DB before: {len(db) - added_toyota - added_generic}")
print(f"Toyota added/updated: {added_toyota} new + {conflict_toyota} conflicts-resolved")
print(f"Generic added (gap fill only): {added_generic}")
print(f"DB after: {len(db)}")

if "--apply" in sys.argv:
    json.dump(db, open(DB, "w"), indent=2, ensure_ascii=False)
    print("APPLIED.")
else:
    print("(run with --apply to write)")
